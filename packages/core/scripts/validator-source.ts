import Ajv2020 from 'ajv/dist/2020';
import standaloneCode from 'ajv/dist/standalone';
import { chalkBoardSchema } from '../src/format/schema';

export const GENERATED_HEADER = '// GENERATED by packages/core/scripts/build-validator.ts — do not edit\n';

/**
 * Compiles the board schema to standalone ESM code (no runtime eval needed to load it).
 * Ajv still emits CommonJS `require` for its small runtime helpers even with esm:true;
 * those are rewritten to ES imports so the file loads in browsers and bundlers.
 */
export function generateValidatorSource(): string {
  const ajv = new Ajv2020({ allErrors: false, code: { source: true, esm: true } });
  const validate = ajv.compile(chalkBoardSchema);
  const imports: string[] = [];
  const code = standaloneCode(ajv, validate).replace(
    /const (\w+) = require\("([^"]+)"\)\.default;/g,
    (_m, name: string, mod: string) => {
      imports.push(`import ${name}_mod from "${mod}.js";`);
      return `const ${name} = ${name}_mod.default ?? ${name}_mod;`;
    },
  );
  if (code.includes('require(')) throw new Error('Generated validator still contains require().');
  return GENERATED_HEADER + imports.join('\n') + (imports.length ? '\n' : '') + code;
}
